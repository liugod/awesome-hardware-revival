def build_category_assets() -> None:
    CATEGORY_ROOT.mkdir(parents=True, exist_ok=True)
    for category, (_, label_en) in CATEGORY_LABELS.items():
        (CATEGORY_ROOT / f"{category}.svg").write_text(category_svg(category, label_en), encoding="utf-8", newline="\n")


def acquire_brand_assets(config: dict) -> None:
    BRAND_ROOT.mkdir(parents=True, exist_ok=True)
    commit = config["simple_icons_commit"]
    for rule in config["brand_rules"]:
        url = f"https://raw.githubusercontent.com/simple-icons/simple-icons/{commit}/icons/{rule['slug']}.svg"
        request = urllib.request.Request(url, headers={"User-Agent": "KitAgain-TRA-22/1.0"})
        with urllib.request.urlopen(request, timeout=30) as response:
            content = response.read()
        target = BRAND_ROOT / f"{rule['slug']}.svg"
        target.write_bytes(content)
        if sha256(target) != rule["sha256"]:
            raise ValueError(f"Brand asset hash mismatch after download: {rule['slug']}")


def matching_brand(record: dict, config: dict, extra_fields: dict[str, str]) -> tuple[dict, str, str] | None:
    fields = {
        "title_zh": record["title_zh"],
        "title_en": record["title_en"],
        "source_url": record["source_url"],
        **extra_fields,
    }
    for rule in config["brand_rules"]:
        for field, value in fields.items():
            folded = value.casefold()
            for token in rule["tokens"]:
                pattern = rf"(?<![a-z0-9]){re.escape(token.casefold())}(?![a-z0-9])"
                if re.search(pattern, folded):
                    return rule, field, token
    return None


def build(*, acquire: bool = False) -> dict:
    missing_data = json.loads(MISSING_PATH.read_text(encoding="utf-8"))
    directory_data = json.loads(DIRECTORY_PATH.read_text(encoding="utf-8"))
    project_image_data = json.loads(PROJECT_IMAGES_PATH.read_text(encoding="utf-8"))
    hardware_tags = json.loads(HARDWARE_TAGS_PATH.read_text(encoding="utf-8"))
    project_leads = {item["id"]: item for item in json.loads(PROJECT_LEADS_PATH.read_text(encoding="utf-8"))["projects"]}
    config = json.loads(OVERRIDES_PATH.read_text(encoding="utf-8"))
    missing = missing_data["entries"]
    directory = {entry["entry_id"]: entry for entry in directory_data["entries"]}
    missing_ids = [entry["entry_id"] for entry in missing]
    if len(missing_ids) != 191 or len(set(missing_ids)) != 191:
        raise ValueError("TRA-19 missing-image input must contain 191 unique entries")
    if not set(missing_ids) <= set(directory):
        raise ValueError("TRA-19 missing-image entry absent from directory data")

    build_category_assets()
    if acquire:
        acquire_brand_assets(config)
    for rule in config["brand_rules"]:
        target = BRAND_ROOT / f"{rule['slug']}.svg"
        if not target.is_file() or sha256(target) != rule["sha256"]:
            raise ValueError(f"Missing or changed brand asset {target}; run with --acquire-brand-assets")

    entries = []
    report_entries = []
    unresolved = []
    for original in missing:
        entry_id = original["entry_id"]
        record = directory[entry_id]
        override = config["entry_overrides"].get(entry_id)
        extra_fields = {}
        if entry_id.startswith("project:"):
            tag_items = hardware_tags["projects"].get(entry_id.removeprefix("project:"), [])
            extra_fields = {"hardware_tags_zh": " ".join(item["zh"] for item in tag_items), "hardware_tags_en": " ".join(item["en"] for item in tag_items)}
        elif entry_id.startswith("lead:"):
            tag_items = hardware_tags["leads"].get(entry_id.removeprefix("lead:"), [])
            extra_fields = {"hardware_tags_zh": " ".join(item["zh"] for item in tag_items), "hardware_tags_en": " ".join(item["en"] for item in tag_items)}
        elif entry_id.startswith("project-lead:"):
            lead = project_leads[entry_id.removeprefix("project-lead:")]
            extra_fields = {"device_scope_zh": lead["device_scope_zh"], "device_scope_en": lead["device_scope_en"], "github_description": lead.get("github_description") or ""}
        brand_match = None if override else matching_brand(record, config, extra_fields)
        if override and override["source_kind"] != "category-illustration":
            unresolved.append({"entry_id": entry_id, "reason": "unsupported manual override"})
            continue
        if brand_match:
            rule, matched_field, token = brand_match
            asset_path = BRAND_ROOT / f"{rule['slug']}.svg"
            local_file = asset_path.relative_to(ROOT / "docs").as_posix()
            kind = "brand-logo"
            label_zh = f"{rule['brand']} 品牌标识"
            label_en = f"{rule['brand']} brand mark"
            source_url = f"https://raw.githubusercontent.com/simple-icons/simple-icons/{config['simple_icons_commit']}/icons/{rule['slug']}.svg"
            license_data = {
                "name": "CC0 1.0 (Simple Icons data); trademarks remain property of their owners",
                "url": f"https://github.com/simple-icons/simple-icons/blob/{config['simple_icons_commit']}/LICENSE.md",
            }
            inference = {"method": "brand-token", "matched_field": matched_field, "matched_token": token, "brand": rule["brand"]}
            category = record["category"]
        else:
            category = override.get("category", record["category"]) if override else record["category"]
            if category not in CATEGORY_LABELS:
                unresolved.append({"entry_id": entry_id, "reason": f"no category illustration for {category}"})
                continue
            label_zh, label_en = CATEGORY_LABELS[category]
            asset_path = CATEGORY_ROOT / f"{category}.svg"
            local_file = asset_path.relative_to(ROOT / "docs").as_posix()
            kind = "category-illustration"
            source_url = f"{REPO}/blob/main/scripts/build_thumbnail_fallbacks.py"
            license_data = {"name": "MIT", "url": f"{REPO}/blob/main/LICENSE-CODE"}
            inference = {
                "method": "manual-override" if override else "directory-category",
                "category": category,
                "reason": override["reason"] if override else "No approved device photo or supported brand mark; use the directory category.",
            }

        alt_zh = f"{label_zh}备用图，非该项目或设备的实拍图"
        alt_en = f"Fallback {label_en}; not a photo of this project or exact device"
        item = {
            "entry_id": entry_id,
            "content_id": original["content_id"],
            "entry_kind": original["entry_kind"],
            "title_zh": original["title_zh"],
            "title_en": original["title_en"],
            "fallback_image": local_file,
            "local_file": local_file,
            "source_kind": kind,
            "fit": "contain",
            "source_url": source_url,
            "license": license_data,
            "alt_zh": alt_zh,
            "alt_en": alt_en,
            "caption_zh": f"备用视觉：{label_zh}；仅帮助识别硬件语境，不是项目成果图或兼容性证明。",
            "caption_en": f"Fallback visual: {label_en}; hardware context only, not project imagery or compatibility evidence.",
            "asset_sha256": sha256(asset_path),
            "inference": inference,
            "original_missing_reason": original["reason"],
        }
        entries.append(item)
        report_entries.append({
            "entry_id": entry_id,
            "title_en": original["title_en"],
            "original_reason": original["reason"],
            "fallback_used": local_file,
            "source_kind": kind,
            "inference": inference,
        })

    entries.sort(key=lambda item: item["entry_id"])
    report_entries.sort(key=lambda item: item["entry_id"])
    counts = collections.Counter(item["source_kind"] for item in entries)
    fallback_kind_counts = {kind: counts.get(kind, 0) for kind in ("hardware-photo", "brand-logo", "category-illustration")}
    existing_kind_counts = dict(sorted(collections.Counter(item["source_kind"] for item in project_image_data["entries"]).items()))
    complete_kind_counts = {**existing_kind_counts, **fallback_kind_counts}
    category_counts = collections.Counter(item["inference"].get("category") for item in entries if item["source_kind"] == "category-illustration")
    brand_counts = collections.Counter(item["inference"].get("brand") for item in entries if item["source_kind"] == "brand-logo")
    ledger = {
        "schema_version": "1.0",
        "version": directory_data["version"],
        "generated_from": ["research/tra-19-directory-image-missing.json", "data/directory.json", "data/hardware-tags.json", "data/project-leads.json", "data/thumbnail-fallback-overrides.json"],
        "policy": "Use an existing item image first; otherwise a local fallback marked as hardware context, never as project imagery.",
        "counts": {"originally_missing": len(missing), "resolved": len(entries), "unresolved": len(unresolved), "by_source_kind": fallback_kind_counts},
        "entries": entries,
    }
    report = {
        "schema_version": "1.0",
        "issue": "TRA-22",
        "baseline": {"listed_entries": directory_data["counts"]["listed_entries"], "existing_real_images": directory_data["counts"]["listed_entries"] - len(missing), "empty_or_placeholder": len(missing), "by_source_kind": existing_kind_counts},
        "after": {"listed_entries": directory_data["counts"]["listed_entries"], "existing_real_images": directory_data["counts"]["listed_entries"] - len(missing), "fallbacks": len(entries), "empty_or_placeholder": len(unresolved), "by_source_kind": complete_kind_counts, "fallback_by_source_kind": fallback_kind_counts, "by_brand": dict(sorted(brand_counts.items())), "by_category": dict(sorted(category_counts.items()))},
        "entries": report_entries,
        "unresolved": unresolved,
    }
    if unresolved or len(entries) != 191:
        raise ValueError(f"Fallback coverage incomplete: {len(entries)} resolved, {len(unresolved)} unresolved")
    dump_json(LEDGER_PATH, ledger)
    dump_json(REPORT_PATH, report)
    return ledger


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--acquire-brand-assets", action="store_true")
    args = parser.parse_args()
    result = build(acquire=args.acquire_brand_assets)
    print(json.dumps(result["counts"], ensure_ascii=False, sort_keys=True))
